FERNET_VALUE_PREFIX = "fernet:v1:"


def _validated_fernet_key() -> bytes:
    if settings.ENCRYPTION_KEY is None:
        raise RuntimeError(
            "ENCRYPTION_KEY is required. Refusing to encrypt without a configured key."
        )

    key = settings.ENCRYPTION_KEY.get_secret_value().encode("utf-8")
    try:
        decoded_key = base64.urlsafe_b64decode(key)
    except (binascii.Error, ValueError) as exc:
        raise RuntimeError(
            "ENCRYPTION_KEY must be a valid Fernet key generated by "
            "Fernet.generate_key()."
        ) from exc
    if len(decoded_key) != 32:
        raise RuntimeError(
            "ENCRYPTION_KEY must be a valid Fernet key generated by "
            "Fernet.generate_key()."
        )
    return key


def get_encryption_keyring() -> EncryptionKeyRing:
    previous_keys = (
        settings.ENCRYPTION_PREVIOUS_KEYS.get_secret_value()
        if settings.ENCRYPTION_PREVIOUS_KEYS is not None
        else None
    )
    return build_encryption_keyring(
        settings.ENCRYPTION_KEY.get_secret_value()
        if settings.ENCRYPTION_KEY is not None
        else None,
        settings.ENCRYPTION_KEY_ID,
        previous_keys,
    )


def get_fernet() -> Fernet:
    return get_encryption_keyring().active_key.fernet


class EncryptedString(TypeDecorator):
    """
    Encrypts string values before saving to the database and decrypts them when
    retrieving.
    Uses Fernet symmetric encryption.
    """

    impl = String
    cache_ok = True

    def process_bind_param(self, value, dialect):
        if value is not None:
            keyring = get_encryption_keyring()
            token = keyring.active_key.fernet.encrypt(value.encode("utf-8")).decode(
                "utf-8"
            )
            return f"{FERNET_VALUE_PREFIX}{keyring.active_key.key_id}:{token}"
        return value

    def process_result_value(self, value, dialect):
        if value is not None:
            keyring = get_encryption_keyring()
            if value.startswith(FERNET_VALUE_PREFIX):
                key_id, _, token = value[len(FERNET_VALUE_PREFIX) :].partition(":")
                encryption_key = keyring.key_for_id(key_id)
                candidate_keys = (encryption_key,) if encryption_key is not None else ()
                ciphertext = token
            else:
                candidate_keys = keyring.all_keys()
                ciphertext = value
            for encryption_key in candidate_keys:
                try:
                    return encryption_key.fernet.decrypt(
                        ciphertext.encode("utf-8")
                    ).decode("utf-8")
                except (InvalidToken, UnicodeDecodeError):
                    continue
            logger.warning("Failed to decrypt field in EncryptedString; returning None")
            return None
        return value


